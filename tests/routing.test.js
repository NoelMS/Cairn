const { chromium } = require('playwright-core');
const assert = require('assert');
(async () => {
  const b = await chromium.launch({ channel: 'chrome', headless: true });
  const p = await b.newPage({ viewport: { width: 1440, height: 900 }, colorScheme: 'dark' });
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()) });
  await p.addInitScript(() => localStorage.setItem('nexus.theme', 'dark'));
  await p.goto('http://127.0.0.1:8765/', { waitUntil: 'networkidle' });
  await p.click('.top-nav [data-go=routing]');
  await p.waitForTimeout(600);
  assert.ok(await p.isVisible('#rt-tutorial'), 'tutorial first time');
  await p.screenshot({ path: __dirname + '/shots/r-tutorial.png' });
  await p.click('#rt-tut-start');
  const sites = await p.$$eval('.rt-chip', n => n.map(e => e.textContent));
  console.log('sites', sites);
  const chip = async name => { await p.locator('.rt-chip', { hasText: name }).click(); };
  await p.click('#rt-dep-HAM');
  await p.locator('.rt-truck').nth(0).locator('.rt-truck-btn').click();
  await chip('Al Dhafra'); await chip('Masdar');
  await p.locator('.rt-truck').nth(1).locator('.rt-truck-btn').click();
  await chip('MBR');
  await p.locator('.rt-truck').nth(2).locator('.rt-truck-btn').click();
  await p.locator('.rt-truck').nth(2).locator('select').selectOption('HAM');
  await chip('Emirates Sustainable'); await chip('National Technology');
  console.log('errs list:', (await p.textContent('#rt-errs')));
  console.log('hud', await p.textContent('#rt-hud-cost'), await p.textContent('#rt-hud-co2'), await p.textContent('#rt-hud-ot'));
  await p.screenshot({ path: __dirname + '/shots/r-plan.png' });
  assert.equal(await p.isDisabled('#rt-score'), false, 'plan feasible');
  await p.click('#rt-score');
  await p.waitForTimeout(500);
  console.log('result:', (await p.textContent('#rt-result-content')).replace(/\s+/g, ' ').slice(0, 420));
  await p.screenshot({ path: __dirname + '/shots/r-result.png' });
  console.log('sensitivity:', await p.textContent('.rt-sens figcaption'));
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('#rt-csv')]);
  const csvPath = __dirname + '/shots/' + dl.suggestedFilename(); await dl.saveAs(csvPath);
  console.log('csv', dl.suggestedFilename()); console.log(require('fs').readFileSync(csvPath, 'utf8').split(String.fromCharCode(10)).slice(0, 5).join(' || '));
  await p.click('#rt-show-opt');
  await p.waitForTimeout(300);
  await p.screenshot({ path: __dirname + '/shots/r-opt.png' });
  await p.click('.rt-scn-btn[data-scn="2"]');
  console.log('ev scenario errs:', await p.textContent('#rt-errs'));
  await p.click('.top-nav [data-go=hub]');
  await p.waitForTimeout(500);
  console.log('hub best', await p.textContent('#stat-routing'));
  const m = await b.newPage({ viewport: { width: 390, height: 844 } });
  await m.addInitScript(() => localStorage.setItem('nexus_routing_tutorial_seen', '1'));
  await m.goto('http://127.0.0.1:8765/', { waitUntil: 'networkidle' });
  await m.click('.top-nav [data-go=routing]'); await m.waitForTimeout(600);
  await m.screenshot({ path: __dirname + '/shots/r-phone.png' });
  console.log('errors', JSON.stringify(errs)); assert.equal(errs.length, 0);
  await b.close(); console.log('ROUTING OK');
})().catch(e => { console.error('FAIL', e.message); process.exit(1); });

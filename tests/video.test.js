const { chromium } = require('playwright-core');
const assert = require('assert');
(async () => {
  const b = await chromium.launch({ channel: 'chrome', headless: true });
  const p = await b.newPage({ viewport: { width: 1440, height: 900 }, colorScheme: 'dark' });
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('response', r => { if (r.status() >= 400) errs.push(r.status() + r.url()); });
  await p.goto('http://127.0.0.1:8765/', { waitUntil: 'networkidle' });
  await p.waitForTimeout(1500);
  const st = () => p.$eval('#intro-video', v => ({ paused: v.paused, t: +v.currentTime.toFixed(2), ready: v.readyState }));
  const a = await st(); console.log('autoplay', a, await p.textContent('#intro-toggle'));
  assert.ok(!a.paused && a.t > 0);
  await p.click('#intro-toggle'); await p.waitForTimeout(200);
  assert.equal((await st()).paused, true); assert.equal(await p.textContent('#intro-toggle'), 'Play');
  await p.click('#intro-toggle'); await p.waitForTimeout(300);
  assert.equal((await st()).paused, false);
  await p.click('.top-nav [data-go=routing]'); await p.waitForTimeout(800);
  console.log('after leaving hub', await st()); assert.equal((await st()).paused, true);
  await p.click('.top-nav [data-go=hub]'); await p.waitForTimeout(800);
  console.log('back on hub', await st()); assert.equal((await st()).paused, false);
  await p.waitForTimeout(3000);
  await p.screenshot({ path: __dirname + '/shots/v-hub-dark.png' });
  const r = await b.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  await r.goto('http://127.0.0.1:8765/', { waitUntil: 'networkidle' }); await r.waitForTimeout(800);
  const rm = await r.$eval('#intro-video', v => v.paused); console.log('reduced motion paused', rm, await r.textContent('#intro-toggle'));
  assert.equal(rm, true);
  await r.screenshot({ path: __dirname + '/shots/v-hub-phone.png', fullPage: false });
  console.log('errors', JSON.stringify(errs)); assert.equal(errs.length, 0);
  await b.close(); console.log('VIDEO OK');
})().catch(e => { console.error('FAIL', e.message); process.exit(1); });
